/* global document, window */
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const { displayProject } = await import('./display-fixture.js');
  const { catalog } = await import('./catalog-fixture.js');
  const { parseProject, serializeProject } = await import('../src/projects/model.js');
  const { generateFirmware, firmwareFingerprint } = await import('../src/firmware/generator.js');
  const project = displayProject();
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CLEX_BROWSER_EXECUTABLE || process.argv[2] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const save = async () => { await page.getByRole('button', { name: 'Сохранить', exact: true }).first().click(); await page.getByText('Проект сохранен', { exact: true }).waitFor(); };
  const stored = () => page.evaluate(() => JSON.parse(Object.values(JSON.parse(localStorage.getItem('clex-flow:projects:v1')))[0]));
  const openEditor = async () => { await page.getByRole('button', { name: 'Логика', exact: true }).click(); await page.locator('.logic-node').dblclick(); await page.getByRole('dialog').waitFor(); };
  try {
    await page.addInitScript(p => { if (!localStorage.getItem('clex-flow:projects:v1')) localStorage.setItem('clex-flow:projects:v1', JSON.stringify({ [p.id]: JSON.stringify(p) })); }, project);
    await page.goto(process.env.CLEX_PREVIEW_URL || 'http://127.0.0.1:1430'); await page.locator('.project-open').click(); await openEditor();
    const dialog = page.getByRole('dialog'), main = dialog.locator('[data-screen-view="main"]'), splash = dialog.locator('[data-screen-view="splash"]');
    const a = await main.boundingBox(), b = await splash.boundingBox();
    assert.ok(b.x < a.x && Math.abs(b.y - a.y) < 2, 'the splash editor is to the left of the main screen');
    const png = await page.evaluate(() => {
      const canvas = document.createElement('canvas'); canvas.width = 120; canvas.height = 60;
      const context = canvas.getContext('2d'); context.fillStyle = '#34d399'; context.font = 'bold 35px sans-serif'; context.fillText('CLEX', 8, 43);
      context.fillStyle = 'rgba(56,189,248,0.5)'; context.fillRect(100,5,10,10);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    const input = dialog.getByLabel('Файл PNG', { exact: true });
    await input.setInputFiles({ name: 'logo.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
    await main.locator('[data-screen-image]').waitFor();
    assert.equal(await dialog.getByLabel('Ширина изображения').inputValue(), '120');
    await dialog.getByLabel('Ширина изображения').fill('80');
    assert.equal(await dialog.getByLabel('Высота изображения').inputValue(), '40');
    const image = main.locator('[data-screen-image]'), initialX = Number(await dialog.getByLabel('Координата X').inputValue()), box = await image.boundingBox();
    await page.mouse.move(box.x+20,box.y+20); await page.mouse.down(); await page.mouse.move(box.x+40,box.y+35,{steps:8}); await page.mouse.up();
    assert.ok(Number(await dialog.getByLabel('Координата X').inputValue()) > initialX);
    await dialog.getByLabel('Заставка при запуске', { exact: true }).check();
    assert.equal(await main.locator('[data-screen-image]').count(), 0); await splash.locator('[data-screen-image]').waitFor();
    await dialog.getByLabel('Время заставки, сек', { exact: true }).fill('1.5');
    const corner = dialog.getByRole('button', { name: 'Изменить размер изображения', exact: true }), cornerBox = await corner.boundingBox();
    await page.mouse.move(cornerBox.x+5,cornerBox.y+5); await page.mouse.down(); await page.mouse.move(cornerBox.x+35,cornerBox.y+20,{steps:8}); await page.mouse.up();
    const width = Number(await dialog.getByLabel('Ширина изображения').inputValue()), height = Number(await dialog.getByLabel('Высота изображения').inputValue());
    assert.ok(width > 80); assert.ok(Math.abs(width / height - 2) < 0.05, 'corner resizing preserves proportions');
    const transparency = await splash.locator('canvas').evaluate(e => e.getContext('2d').getImageData(0,0,1,1).data[3]);
    assert.equal(transparency, 0);
    await page.screenshot({ path: '.artifacts/png-splash-editor.png' });
    await dialog.getByRole('button', { name: 'Сохранить интерфейс', exact: true }).click(); await save();
    const result = await stored(), id = project.components[0].id, asset = result.screens[id].elements.find(e => e.type === 'image');
    assert.equal(asset.durationMs, 1500); assert.equal(asset.splash, true);
    assert.deepEqual(parseProject(serializeProject(result)).screens, result.screens);
    const fingerprint = await firmwareFingerprint(generateFirmware(result,catalog));
    await page.reload(); await page.locator('.project-open').click(); await openEditor();
    await splash.locator('[data-screen-image]').click();
    assert.equal(await dialog.getByLabel('Время заставки, сек').inputValue(), '1.5');
    await input.setInputFiles({name:'invalid.png',mimeType:'image/png',buffer:Buffer.from('not PNG')});
    await dialog.getByRole('alert').filter({hasText:'PNG'}).waitFor();
    assert.equal(await splash.locator('[data-screen-image]').count(),1);
    await dialog.getByLabel('Заставка при запуске').uncheck();
    assert.equal(await splash.locator('[data-screen-image]').count(),0); assert.equal(await main.locator('[data-screen-image]').count(),1);
    await dialog.getByRole('button',{name:'Отмена',exact:true}).click();
    assert.equal(await firmwareFingerprint(generateFirmware(await stored(),catalog)),fingerprint,'cancel keeps the saved image and timing');
    await openEditor(); await page.setViewportSize({width:1000,height:700});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
    await page.screenshot({path:'.artifacts/png-splash-editor-small.png'});
    await dialog.getByRole('button',{name:'Отмена',exact:true}).click();
    assert.deepEqual(errors,[]);
    console.log('PASS: real PNG import, transparency, proportional field/corner resizing, dragging, side-by-side main/splash, duration, JSON save/reload, invalid file rejection and cancel.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
